BASE_SHA = 'f974e4a1e44ae758ba748fc91838cd820cfb807ed4c09e7ffa5dc661d267565e'
EXPECTED = {'A':360,'B':5096,'D_UTU':6576,'D_UTT':6576,'D_TTU':18204,'D_TTT':18204}
ROLES = {'0':'P15','1':'D9_FIRST4','2':'D9_SECOND4','None':'D10'}

def need(ok, message):
    if not ok:
        raise ValueError(message)

def sha(raw):
    return hashlib.sha256(raw).hexdigest()

def pin(path):
    raw = path.read_bytes()
    return {'path':str(path),'bytes':len(raw),'sha256':sha(raw)}

def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--inputs',type=Path,required=True)
    p.add_argument('--emission',type=Path,required=True)
    p.add_argument('--output',type=Path,required=True)
    a = p.parse_args()
    need(not a.output.exists(),'Refusing to replace a binding result')
    start = time.process_time()
    package = Path(__file__).resolve().parents[1]
    source = PAIR_ORDER
    raw = json.dumps(source,separators=(',',':')).encode('ascii')
    need(sha(raw)==PAIR_ORDER_SHA,'Finite pair-order literal mismatch')
    need(len(source)==737,'Wrong source pair census')
    manifest = json.loads((a.inputs/'MANIFEST.json').read_text())
    base = (a.inputs/'base.clauses').read_bytes()
    need(sha(base)==BASE_SHA==manifest['base']['sha256'],'Input base differs')
    catalog_path = a.inputs/'cases.jsonl.gz'
    need(pin(catalog_path)['sha256']==manifest['catalog']['sha256'],'Input catalog pin differs')
    expected={}
    with gzip.open(catalog_path,'rt') as stream:
        for line in stream:
            row=json.loads(line)
            if row['family'] not in EXPECTED:
                continue
            key=row['family'],row['case_id']
            need(key not in expected,'Duplicate input catalog owner')
            expected[key]=row
    need(dict(collections.Counter(f for f,c in expected))==EXPECTED,'Production common census differs')
    states={};seen=set();pairs=set();count=collections.Counter();pins=[];ordered=hashlib.sha256()
    files=sorted(a.emission.glob('*.tsv'))
    need(files,'Missing Lean emission')
    for path in files:
        raw=path.read_bytes()
        need(len(raw)<=64<<20,'Oversized metadata shard')
        pins.append(pin(path))
        lines=raw.decode('ascii').splitlines()
        head=lines[0].split('\t')
        need(len(head)==8 and head[0]=='PAIR','Malformed Lean shard header')
        _,pidx,profile,owner,lk,rk,stage,n=head
        pidx,lk,rk,stage,n=map(int,(pidx,lk,rk,stage,n))
        need(0<=pidx<737 and (pidx,owner) not in pairs,'Duplicate or invalid pair/owner')
        pairs.add((pidx,owner))
        fam,kind,s,idx=source[pidx]
        need(profile==fam and owner[:2]==kind,'Native case source/owner mismatch')
        need((lk,rk,stage)==((2 if fam=='A' else 0)+(kind[0]=='T'),
                             (2 if fam in ('A','B') else 0)+(kind[1]=='T'),3 if s=='None' else int(s)),
             'Native profile/shape metadata mismatch')
        need(len(lines)==n+1,'Truncated or extra Lean leaf lines')
        row_ids=set()
        for line in lines[1:]:
            fields=line.split('\t')
            need(len(fields)==3 and fields[0]=='LEAF','Malformed Lean unit row')
            j=int(fields[1]);need(0<=j<n and j not in row_ids,'Duplicate or invalid representative')
            row_ids.add(j)
            role=ROLES[s]
            family=fam if fam!='D' else 'D_'+owner
            if fam=='D' and role=='P15':role='P15_MATRIX_ONLY'
            cid=(fam+'_'+owner if fam!='D' else owner)+f'/{role}/pair_{idx:03d}/rep_{j:03d}'
            key=family,cid
            need(key in expected and key not in seen,'Unknown or duplicate physical case: '+str(key))
            seen.add(key)
            units=list(map(int,fields[2].split(',')))
            row=expected[key]
            need(units==row['units'],'Ordered unit mismatch: '+str(key))
            need(all(0<abs(x)<=7320 for x in units),'Non-edge literal')
            suffix=''.join(f'{u} 0\n' for u in units).encode('ascii')
            k=len(units)
            if k not in states:
                prefix=f'p cnf 7320 {156770+k}\n'.encode()+base
                states[k]=(hashlib.sha256(prefix),len(prefix))
            state,size=states[k];h=state.copy();h.update(suffix)
            observed={'sha256':h.hexdigest(),'bytes':size+len(suffix),'variables':7320,'clauses':156770+k}
            need(observed==row['formula'],'Formula metadata mismatch: '+str(key))
            ordered.update((family+'\t'+cid+'\t'+h.hexdigest()+'\n').encode())
            count[family]+=1
    need(seen==set(expected),'Incomplete common case binding')
    need({p for p,o in pairs}==set(range(737)),'Incomplete finite pair binding')
    result={'schema':'UNIFORM_K61_COMMON_BINDING_1','status':'PASS_ALL_55016_UNIFORM_COMMON_INPUTS',
            'cases':len(seen),'family_counts':dict(count),'retained_pairs':737,'pair_owner_shards':len(files),
            'ordered_case_hashes_sha256':ordered.hexdigest(),'CPU_seconds':time.process_time()-start,
            'inputs_manifest':pin(a.inputs/'MANIFEST.json'),'catalog':pin(catalog_path),
            'base':pin(a.inputs/'base.clauses'),
            'pair_order':{'pairs':737,'sha256':PAIR_ORDER_SHA},
            'emitter':pin(package/'uniform/EmitCommon.lean'),'checker':pin(Path(__file__)),
            'cache_source':pin(package.parents[0]/'src/UniformK61/CommonUnitCache.lean'),
            'emission_shards':pins,
            'scope':'Exact ordered Lean units, complete case-ID bijection, and full formula hashes. Shared Lean base binding is separate. No solver runs.'}
    a.output.parent.mkdir(parents=True,exist_ok=True)
    with a.output.open('x') as stream:json.dump(result,stream,indent=2);stream.write('\n')
    print(json.dumps({k:v for k,v in result.items() if k!='emission_shards'},indent=2))

if __name__=='__main__':
    main()
